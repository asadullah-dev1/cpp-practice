#include <iostream>
using namespace std;

int main() {
    int num1, num2;

    cout << "Enter two integers: " << endl;
    cin >> num1 >> num2;

    cout << "The sum is: " << num1 + num2 << endl;
    cout << "The subtraction is: " << num1 - num2 << endl;
    cout << "The division is: " << num1 / num2 << endl;
    cout << "The multiplication is: " << num1 * num2 << endl;

    return 0;
}